export const regeneratePitch = async (req, res) => {
  try {
    const { id } = req.params;
    const { instructions, tone } = req.body;

    const message = await Message.findById(id).populate({
      path: 'lead_id',
      populate: { path: 'analysis' }
    });
    if (!message || !message.lead_id) return res.status(404).json({ success: false, error: 'Message or Lead not found' });

    const lead = message.lead_id;
    const analysis = lead.analysis;

    const prompt = `
Regenerate cold outreach email for ${lead.business_name} (${lead.industry}, ${lead.city || 'India'}).
Tone: ${tone || 'Persuasive, highly tailored, direct and concise'}.
Special Instructions: ${instructions || 'Emphasize fast delivery and immediate appointment booking growth'}.
Key Observations: ${analysis?.pain_points?.join(', ') || 'No modern booking workflow'}.

Return JSON:
{
  "subject": "Tailored subject line",
  "body": "Hi ${lead.business_name} team,\\n\\n..."
}
`;

    const response = await aiService.executeWithFallback(prompt, 'You are an elite B2B email copywriter.', 'MESSAGE_GEN', lead._id);
    let newSubject = `Opportunity for ${lead.business_name}'s website`;
    let newBody = `Hi ${lead.business_name} team,\n\nI was looking into ${lead.industry} in ${lead.city || 'your area'} and noticed a clear opportunity to modernize your patient appointment flow.\n\nAt Leovexa Technologies, we implement automated booking systems that convert visitors directly into confirmed inquiries.\n\nWould you be open to a 2-minute quick walkthrough this week?\n\nBest regards,\nLeovexa Technologies`;

    try {
      const parsed = JSON.parse(response.text.match(/\{[\s\S]*\}/)?.[0]);
      if (parsed.subject) newSubject = parsed.subject;
      if (parsed.body) newBody = parsed.body;
    } catch (e) {}

    message.subject = newSubject;
    message.content = newBody;
    message.status = 'PENDING_APPROVAL';
    await message.save();

    res.json({ success: true, message: 'Pitch regenerated by AI', data: message });
  } catch (error) {
    res.status(500).json({ success: false, error: error.message });
  }
};

