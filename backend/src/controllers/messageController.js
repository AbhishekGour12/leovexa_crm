// Get Multi-Touch Follow-up Sequences across all contacted/active leads
export const getFollowupSequences = async (req, res) => {
  try {
    const leads = await Lead.find({
      status: { $in: ['CONTACTED', 'QUALIFIED', 'APPROVED', 'MEETING_BOOKED', 'CONVERTED'] }
    }).sort({ updated_at: -1 }).limit(50);

    const sequences = [];
    for (const lead of leads) {
      const messages = await Message.find({ lead_id: lead._id }).sort({ created_at: 1 });
      const initial = messages.find(m => m.type === 'INITIAL');
      const followup1 = messages.find(m => m.type === 'FOLLOWUP_1');
      const followup2 = messages.find(m => m.type === 'FOLLOWUP_2');

      // Compute schedule & current step
      let currentStep = 'Step 1: Initial Outreach';
      let nextAction = 'Initial pitch sending';
      let nextRunDate = null;

      if (initial && initial.status === 'SENT') {
        const sentDate = new Date(initial.sent_at || initial.delivered_at || initial.created_at);
        const day3Date = new Date(sentDate.getTime() + 3 * 24 * 60 * 60 * 1000);
        const day7Date = new Date(sentDate.getTime() + 7 * 24 * 60 * 60 * 1000);

        if (!followup1) {
          currentStep = 'Step 1: Contacted (Waiting for Day 3)';
          nextAction = 'Automated Day 3 Value Follow-up';
          nextRunDate = day3Date;
        } else if (followup1.status === 'SENT') {
          if (!followup2) {
            currentStep = 'Step 2: Day 3 Sent (Waiting for Day 7)';
            nextAction = 'Automated Day 7 Breakup Pitch';
            nextRunDate = day7Date;
          } else {
            currentStep = 'Step 3: Full 3-Touch Sequence Completed';
            nextAction = 'Sequence Finished';
            nextRunDate = null;
          }
        } else {
          currentStep = 'Step 2: Day 3 Follow-up Queued';
          nextAction = 'Pending Dispatch';
          nextRunDate = day3Date;
        }
      }

      sequences.push({
        lead_id: lead._id,
        business_name: lead.business_name,
        email: lead.email,
        country: lead.country || 'USA',
        lead_score: lead.lead_score,
        lead_status: lead.status,
        current_step: currentStep,
        next_action: nextAction,
        next_run_date: nextRunDate,
        steps: {
          initial: initial ? { id: initial._id, status: initial.status, subject: initial.subject, content: initial.content, sent_at: initial.sent_at } : null,
          followup_1: followup1 ? { id: followup1._id, status: followup1.status, subject: followup1.subject, content: followup1.content, sent_at: followup1.sent_at } : null,
          followup_2: followup2 ? { id: followup2._id, status: followup2.status, subject: followup2.subject, content: followup2.content, sent_at: followup2.sent_at } : null
        }
      });
    }

    res.json({
      success: true,
      count: sequences.length,
      data: sequences
    });
  } catch (error) {
    res.status(500).json({ success: false, error: error.message });
  }
};

// Manually Trigger Instant Follow-up Dispatch for a Lead
export const triggerManualFollowup = async (req, res) => {
  try {
    const { lead_id, step = 'FOLLOWUP_1' } = req.body;
    if (!lead_id) return res.status(400).json({ success: false, error: 'lead_id is required' });

    const lead = await Lead.findById(lead_id);
    if (!lead) return res.status(404).json({ success: false, error: 'Lead not found' });

    const prompt = `
Generate a quick, polite, non-pushy ${step === 'FOLLOWUP_2' ? 'Day 7 Final / Breakup' : 'Day 3 Value Bump'} cold email for Leovexa Technologies (https://leovexa.in).
Lead: ${lead.business_name} in ${lead.city || 'local area'} (${lead.industry}).
Keep it concise, high-converting, under 60 words.

Return JSON:
{
  "subject": "${step === 'FOLLOWUP_2' ? 'Final note regarding' : 'Quick follow-up on'} ${lead.business_name}'s website / booking flow",
  "body": "Hi ${lead.business_name} team,\\n\\n..."
}
`;

    const response = await aiService.executeWithFallback(prompt, 'You are an email copywriter.', 'MESSAGE_GEN', lead._id);
    let json = {
      subject: `Following up on ${lead.business_name}'s website`,
      body: `Hi ${lead.business_name} team,\n\nFollowing up briefly on my earlier note. Have you had a chance to review ideas for updating ${lead.business_name}'s online patient booking flow?\n\nHappy to share a quick 2-minute video audit if you're open.\n\nBest,\nLeovexa Team\nhttps://leovexa.in`
    };

    try {
      const parsed = JSON.parse(response.text.match(/\{[\s\S]*\}/)?.[0]);
      if (parsed.subject && parsed.body) json = parsed;
    } catch (e) {}

    const msg = await Message.create({
      lead_id: lead._id,
      campaign_id: lead.campaign_id,
      channel: 'EMAIL',
      direction: 'OUTBOUND',
      type: step,
      subject: json.subject,
      content: json.body,
      status: 'APPROVED',
      approval_source: 'WEB_DASHBOARD',
      ai_generated: true
    });

    // Immediate dispatch via Gmail
    emailService.sendEmail({
      to: lead.email,
      subject: msg.subject,
      text: msg.content,
      messageId: msg._id,
      leadId: lead._id
    }).catch(e => console.warn('Manual followup dispatch notice:', e.message));

    res.json({
      success: true,
      message: `${step === 'FOLLOWUP_2' ? 'Day 7 Final' : 'Day 3'} Follow-up drafted and queued for live sending to ${lead.email}!`,
      data: msg
    });
  } catch (error) {
    res.status(500).json({ success: false, error: error.message });
  }
};
