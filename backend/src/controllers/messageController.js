export const approveMessage = async (req, res) => {
  try {
    const { id } = req.params;
    const { content, subject } = req.body;

    const message = await Message.findById(id).populate('lead_id');
    if (!message) return res.status(404).json({ success: false, error: 'Message not found' });

    if (content) message.content = content;
    if (subject) message.subject = subject;
    message.status = 'APPROVED';
    message.approval_source = 'WEB_DASHBOARD';
    await message.save();

    if (message.lead_id) {
      message.lead_id.status = 'APPROVED';
      await message.lead_id.save();
    }

    // Immediately dispatch via Email service
    emailService.sendEmail({
      to: message.lead_id.email,
      subject: message.subject,
      text: message.content,
      messageId: message._id,
      leadId: message.lead_id._id
    }).catch(e => console.warn('Email dispatch warning:', e.message));

    res.json({ success: true, message: 'Message approved and queued for sending', data: message });
  } catch (error) {
    res.status(500).json({ success: false, error: error.message });
  }
};

